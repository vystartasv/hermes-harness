/**
 * pr-creator.ts — Create PRs from queued improvement proposals
 * Scans ~/.hermes/harness/pending-prs/ and submits PRs via GitHub API.
 */
import { readFileSync, readdirSync, unlinkSync, existsSync } from "fs";
import { join } from "path";
import { homedir } from "os";
import { callFreeLLM, HarnessProposal } from "./harness";

const HERMES_HOME = join(homedir(), ".hermes");
const PR_DIR = join(HERMES_HOME, "harness", "pending-prs");

async function generatePRContent(proposal: HarnessProposal): Promise<{ title: string; body: string; branch: string }> {
  const prompt = `Generate a GitHub PR for the configured repository.

Fix proposal:
- Type: ${proposal.type}
- Target: ${proposal.target}
- Reason: ${proposal.reason}
- Content: ${proposal.content?.slice(0, 500)}

Return JSON:
{ "title": "fix(harness): concise PR title",
  "body": "detailed PR description with problem, solution, testing",
  "branch": "fix/harness-auto-<short-description>" }`;

  const raw = await callFreeLLM(prompt);
  try {
    return JSON.parse(raw);
  } catch {
    return {
      title: `fix(harness): ${proposal.target}`,
      body: `## Problem\n\n${proposal.reason}\n\n## Solution\n\n${proposal.content?.slice(0, 1000) || "Auto-generated by Hermes Harness"}`,
      branch: `fix/harness-auto-${Date.now()}`,
    };
  }
}

async function submitPR(pr: { title: string; body: string; branch: string }): Promise<boolean> {
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  if (!token) {
    console.log("No GitHub token — PR saved locally");
    return false;
  }

  const target = process.env.HARNESS_TARGET_REPO;
  const head = process.env.HARNESS_PR_HEAD;
  if (!target || !head) {
    console.log("Set HARNESS_TARGET_REPO and HARNESS_PR_HEAD to enable PR submission");
    return false;
  }
  const resp = await fetch(`https://api.github.com/repos/${target}/pulls`, {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${token}`,
      "Content-Type": "application/json",
      "Accept": "application/vnd.github.v3+json",
    },
    body: JSON.stringify({
      title: pr.title,
      body: pr.body,
      head,
      base: process.env.HARNESS_PR_BASE || "main",
    }),
  });

  if (resp.ok) {
    const data = await resp.json() as any;
    console.log(`✅ PR created: ${data.html_url}`);
    return true;
  } else {
    const err = await resp.text();
    console.error(`PR failed: ${err}`);
    return false;
  }
}

async function main() {
  if (!existsSync(PR_DIR)) {
    console.log("No pending PRs");
    return;
  }

  const files = readdirSync(PR_DIR).filter(f => f.endsWith(".json"));
  for (const file of files) {
    const proposal: HarnessProposal = JSON.parse(readFileSync(join(PR_DIR, file), "utf-8"));
    console.log(`Generating PR for: ${proposal.target}`);

    const pr = await generatePRContent(proposal);
    const submitted = await submitPR(pr);

    if (submitted) {
      unlinkSync(join(PR_DIR, file));
    } else {
      // Save PR content alongside for manual review
      const outDir = join(HERMES_HOME, "harness", "generated-prs");
      const { writeFileSync, mkdirSync } = await import("fs");
      mkdirSync(outDir, { recursive: true });
      writeFileSync(join(outDir, `${file.replace(".json", ".md")}`), 
        `# ${pr.title}\n\n${pr.body}\n\n---\nBranch: ${pr.branch}\n`);
      console.log(`📄 PR saved to generated-prs/`);
    }
  }
}

main().catch(console.error);
